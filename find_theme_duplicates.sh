#!/bin/bash

echo "========================================"
echo "🔍 Finding ALL Theme.swift files"
echo "========================================"
echo ""

echo "All files named Theme.swift:"
find . -name "Theme.swift" -type f 2>/dev/null | grep -v ".build/" | grep -v "DerivedData"

echo ""
echo "========================================"
echo "📄 Files containing 'struct Theme' or 'enum Theme'"
echo "========================================"
echo ""

echo "Searching for Theme declarations:"
grep -r "struct Theme\|enum Theme" --include="*.swift" . 2>/dev/null | grep -v "Binary file" | grep -v ".build/" | grep -v "DerivedData"

echo ""
echo "========================================"
echo "🎯 Expected Result"
echo "========================================"
echo ""
echo "You should have EXACTLY TWO Theme files:"
echo "  1. ./Theme.swift (for iOS app - RaceTrian target)"
echo "  2. ./appwatch Watch App/Theme.swift (for Watch app - appwatch target)"
echo ""
echo "If you see MORE than two files, or if both are NOT in separate folders,"
echo "that's causing the 'Multiple commands produce' error!"
echo ""
echo "========================================"
echo "🔧 How to Fix"
echo "========================================"
echo ""
echo "In Xcode:"
echo "  1. Click the blue project icon at the top of Project Navigator"
echo "  2. Select 'RaceTrian' target"
echo "  3. Go to 'Build Phases' tab"
echo "  4. Expand 'Compile Sources'"
echo "  5. Look for TWO entries that say 'Theme.swift'"
echo "  6. Remove the one that says 'appwatch Watch App' or has a Watch folder path"
echo "  7. Then: Clean Build Folder (⌘⇧K) → Quit Xcode → Delete DerivedData → Rebuild"
echo ""
